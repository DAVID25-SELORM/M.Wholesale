// Writes docs/ACCESS_REVIEW.md: who can do what, per built-in role, straight from the database, plus separation-of-duties checks.
//   node scripts/db-test.mjs --migrate-only      (migrate the local test database)
//   node scripts/role-matrix.mjs                  (regenerate the document)
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import pg from 'pg'
import { adminConfig } from './lib/db.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const db = new pg.Client(adminConfig('wps_test'))
await db.connect()

const roles = (await db.query(`select id, code, name, description from public.roles where organization_id is null order by code`)).rows
const perms = (await db.query(`select code, module, action, description from public.permissions order by module, action`)).rows
const grants = (await db.query(`select r.code as role, p.code as perm from public.role_permissions rp join public.roles r on r.id = rp.role_id and r.organization_id is null join public.permissions p on p.id = rp.permission_id`)).rows
await db.end()

const has = new Map(roles.map((r) => [r.code, new Set(grants.filter((g) => g.role === r.code).map((g) => g.perm))]))
const modules = [...new Set(perms.map((p) => p.module))]

// pairs of permissions that one person should not hold together (one person doing both removes the second pair of eyes)
const conflicts = [
  ['purchasing.create', 'purchasing.approve', 'raises AND approves purchase orders'],
  ['payables.create', 'payables.approve', 'records AND approves supplier invoices'],
  ['payables.approve', 'payables.pay', 'approves AND pays supplier invoices'],
  ['inventory.adjust', 'inventory.count_approve', 'adjusts stock AND approves stock counts'],
  ['sales.post', 'sales.reverse', 'posts AND reverses invoices'],
  ['receipts.create', 'receipts.void', 'takes AND voids customer payments'],
  ['receipts.create', 'refunds.create', 'takes money AND pays it back'],
  ['credit_notes.create', 'credit_notes.post', 'drafts AND posts credit notes'],
  ['sales.discount', 'sales.price_override', 'gives discounts AND overrides prices'],
  ['sales.override_credit', 'receipts.void', 'overrides credit limits AND voids payments'],
]
const code = (s) => '`' + s + '`'
const out = []
out.push('# Access review: who can do what', '', 'Generated by `scripts/role-matrix.mjs` from the migrations (built-in roles). Re-run it after any permission change. Branch scope is separate: a role is assigned to a user either organisation-wide or for one branch.', '')
out.push(`${roles.length} built-in roles, ${perms.length} permissions.`, '')

out.push('## Separation-of-duties check', '', 'Roles that hold both halves of a pairing that normally needs two people. These are not necessarily wrong (an owner must be able to do everything) but each should be a conscious decision.', '')
const rows = []
for (const r of roles) for (const [a, b, why] of conflicts) if (has.get(r.code).has(a) && has.get(r.code).has(b)) rows.push([r.code, why, `${code(a)} + ${code(b)}`])
out.push('| Role | Can do both | Permissions |', '|---|---|---|', ...rows.map((r) => `| ${r[0]} | ${r[1]} | ${r[2]} |`), '')
const nonOwner = rows.filter((r) => !['OWNER', 'SUPER_ADMIN', 'GENERAL_MANAGER'].includes(r[0]))
out.push(nonOwner.length === 0 ? 'Apart from the three top roles (owner, super admin, general manager) no built-in role holds a conflicting pair.' : `Outside the three top roles, ${nonOwner.length} pairing(s) above deserve a look.`, '')

out.push('## Role by role', '')
for (const r of roles) {
  const mine = has.get(r.code)
  out.push(`### ${r.code}${r.name ? ` — ${r.name}` : ''}`, '')
  if (r.description) out.push(r.description, '')
  const parts = modules.map((m) => {
    const ps = perms.filter((p) => p.module === m && mine.has(p.code))
    return ps.length ? `**${m}**: ${ps.map((p) => p.action).join(', ')}` : null
  }).filter(Boolean)
  out.push(parts.length ? parts.join(' · ') : '_no permissions_', '')
}

out.push('## Permission by role', '', `| Permission | ${roles.map((r) => r.code).join(' | ')} |`, `|---|${roles.map(() => ':-:').join('|')}|`)
for (const p of perms) out.push(`| ${code(p.code)} | ${roles.map((r) => (has.get(r.code).has(p.code) ? '●' : '')).join(' | ')} |`)
out.push('')

out.push('## Who holds the sensitive rights', '')
for (const [perm, label] of [
  ['users.invite', 'invite users'], ['roles.assign', 'assign roles'], ['audit.view', 'read the audit log'], ['reports.margins', 'see cost prices and margins'], ['inventory.valuation', 'see stock valuation'],
  ['sales.override_credit', 'override credit limits'], ['sales.reverse', 'reverse invoices'], ['credit_notes.reverse', 'reverse credit notes'], ['refunds.create', 'pay customers back'],
  ['receipts.void', 'void customer payments'], ['inventory.adjust', 'adjust stock'], ['registers.controlled', 'read the controlled-drugs register'], ['pos.manage', 'close other cashiers\' till shifts'],
]) {
  const who = roles.filter((r) => has.get(r.code).has(perm)).map((r) => r.code)
  out.push(`- **${label}** (${code(perm)}): ${who.length ? who.join(', ') : 'nobody'}`)
}
out.push('')
writeFileSync(join(root, 'docs', 'ACCESS_REVIEW.md'), out.join('\n'))
console.log(`wrote docs/ACCESS_REVIEW.md (${roles.length} roles, ${perms.length} permissions, ${rows.length} conflicting pairings)`)
